export function getItemCategoryById(id: ItemCategoryId): ItemCategory {
  const category = ITEM_CATEGORIES.find((entry) => entry.id === id)
  if (!category) throw new Error(`Unknown item category: ${id}`)
  return category
}

export function getItemCategory(itemId: number): ItemCategory | null {
  if (!Number.isInteger(itemId) || itemId <= 0) return null
  const prefix = (itemId >> 8) & 0xff
  return ITEM_CATEGORIES.find((entry) => entry.prefix === prefix) ?? null
}

export function getItemName(itemId: number): string {
  const category = getItemCategory(itemId)
  if (!category) return ''
  const index = (itemId & 0xff) - 1
  if (index < 0 || index >= category.slotCount) return ''
  return ITEM_NAMES[category.nameOffset + index] ?? ''
}

export function getItemId(category: ItemCategory, index: number): number {
  return (category.prefix << 8) | (index + 1)
}

export function isItemIdInCategory(itemId: number, category: ItemCategory): boolean {
  return ((itemId >> 8) & 0xff) === category.prefix && (itemId & 0xff) >= 1 && (itemId & 0xff) <= category.slotCount
}
