// Item names decoded from the game's sfc_item.msg text table (English entries).
// The table stores an English name followed by a French name for every item;
// only the English entry is used here. Names are indexed by category + (id & 0xff) - 1.

export type ItemCategoryId =
  | 'weapon' | 'armor' | 'helmet' | 'accessory' | 'consumable' | 'important'

export interface ItemCategory {
  id: ItemCategoryId
  label: string
  /** High byte of the in-save item id (0x00, 0x10, ...). */
  prefix: number
  /** Index of this category's first name in ITEM_NAMES. */
  nameOffset: number
  /** Number of inventory slots reserved for this category. */
  slotCount: number
  /** Offset of the category's first slot inside a save slot. */
  offset: number
}

